// Repository-level guards that are deliberately not exposed over HTTP.
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
require('reflect-metadata')
const esbuild = require('../../node_modules/esbuild')
const {PrismaClient} = require('@prisma/client')
const filename = process.env.DECK_SETTINGS_TEST_DB
assert(filename && !filename.endsWith('/flashnext.db'), 'Use a disposable migrated DB')
process.env.DATABASE_URL = `file:${filename}`
const prisma = new PrismaClient()
const outfile = path.resolve(__dirname,'../../node_modules/.cache/deck-settings-repository.cjs')
fs.mkdirSync(path.dirname(outfile), {recursive:true})
esbuild.buildSync({entryPoints:[path.resolve(__dirname,'../../app/modules/fsrs/infrastructure/fsrs.repository.ts')],bundle:true,platform:'node',format:'cjs',packages:'external',outfile,tsconfig:path.resolve(__dirname,'../../tsconfig.json')})
const {FsrsRepository}=require(outfile)
const repo=new FsrsRepository()
const {ensureDeckConfig}=require('../lib/deck-config')
;(async()=> {
  const first=await prisma.deck.create({data:{name:'repository guard A'}})
  const other=await prisma.deck.create({data:{name:'repository guard B'}})
  await ensureDeckConfig(prisma,first.id);await ensureDeckConfig(prisma,other.id)
  const a=await prisma.card.create({data:{deckId:first.id,front:'A',back:'A'}})
  const b=await prisma.card.create({data:{deckId:other.id,front:'B',back:'B'}})
  await prisma.reviewLog.create({data:{cardId:a.id,rating:3}})
  await prisma.reviewLog.create({data:{cardId:b.id,rating:4}})
  const csv=await repo.buildRevlogCsv(first.id)
  assert.equal(csv.rows,1)
  assert.equal(Number(csv.csv.trim().split('\n')[1].split(',')[1]),a.id)
  assert.equal((await repo.buildRevlogCsv(first.id,new Set([b.id]))).rows,0)
  assert.equal(await repo.countLogs(other.id),1)
  const param=await repo.getParamRow(first.id)
  const before=await repo.getParamRow(other.id)
  const weights=JSON.parse(param.w)
  await prisma.deckSetting.update({where:{deckId:first.id},data:{version:{increment:1}}})
  await assert.rejects(()=>repo.saveParams(first.id,weights,'manual',{settings:0,params:0}),/重新训练/)
  assert.deepEqual(await repo.getParamRow(first.id),param)
  await repo.saveParams(first.id,weights,'manual',{settings:1,params:0})
  await assert.rejects(()=>repo.saveParams(first.id,weights,'manual',{settings:1,params:0}),/重新训练/)
  assert.deepEqual(await repo.getParamRow(other.id),before)
  await prisma.deck.delete({where:{id:first.id}})
  await assert.rejects(()=>repo.saveParams(first.id,weights,'manual',{settings:1,params:1}),/牌组已删除/)
  assert.equal(await prisma.deckFsrsParam.findUnique({where:{deckId:first.id}}),null)
  await prisma.deck.delete({where:{id:other.id}})
  console.log('PASS training CSV isolation; stale settings/weights reject training writeback; deleted decks cannot resurrect')
})().catch(e=>{console.error(e);process.exitCode=1}).finally(async()=>{await prisma.$disconnect();process.exit(process.exitCode||0)})
